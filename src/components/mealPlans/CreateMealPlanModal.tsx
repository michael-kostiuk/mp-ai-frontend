import React, { useState, useEffect } from 'react';
import { X, Calendar, Users, Target, Plus, Trash2 } from 'lucide-react';
import { MealPlanCreate, MealPlanEntryCreate, Recipe, MealPlan } from '../../types';
import Button from '../ui/Button';
import Input from '../ui/Input';
import Select from '../ui/Select';
import Card, { CardContent, CardHeader, CardTitle } from '../ui/Card';
import RecipeSearchSelect from '../recipes/RecipeSearchSelect';
import useApi from '../../hooks/useApi';
import { getRecipes } from '../../api/recipeApi';
import { createMealPlan, autoGenerateMealPlan, updateMealPlan } from '../../api/mealPlanApi';

interface CreateMealPlanModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSuccess: () => void;
  editingMealPlan?: MealPlan | null;
}

const CreateMealPlanModal: React.FC<CreateMealPlanModalProps> = ({
  isOpen,
  onClose,
  onSuccess,
  editingMealPlan = null
}) => {
  const isEditing = !!editingMealPlan;
  const [isAutoGenerate, setIsAutoGenerate] = useState(false);
  const [formData, setFormData] = useState<MealPlanCreate>({
    start_date: '',
    end_date: '',
    people_count: 2,
    target_calories: 2000,
    dietary_preferences: [],
    entries: []
  });
  
  const [autoGenerateData, setAutoGenerateData] = useState({
    start_date: '',
    days: 7,
    target_calories: 2000,
    people_count: 2,
    dietary_preferences: [] as string[],
    user_id: 1
  });

  const { data: recipes, execute: fetchRecipes } = useApi<Recipe[]>(getRecipes);
  const { loading: creating, execute: createPlan } = useApi(createMealPlan);
  const { loading: updating, execute: updatePlan } = useApi(updateMealPlan);
  const { loading: autoGenerating, execute: autoGenerate } = useApi(autoGenerateMealPlan);

  // Initialize form data when editing meal plan changes
  useEffect(() => {
    if (editingMealPlan) {
      const startDate = editingMealPlan.start_date.split('T')[0];
      const endDate = editingMealPlan.end_date.split('T')[0];
      
      setFormData({
        start_date: startDate,
        end_date: endDate,
        people_count: editingMealPlan.people_count,
        target_calories: editingMealPlan.target_calories,
        dietary_preferences: [...editingMealPlan.dietary_preferences],
        entries: editingMealPlan.entries.map(entry => ({
          recipe_id: entry.recipe_id,
          date: entry.date.split('T')[0],
          meal_type: entry.meal_type,
          servings: entry.servings
        }))
      });
      
      // Disable auto-generate mode when editing
      setIsAutoGenerate(false);
    } else {
      // Reset form for new meal plan
      setFormData({
        start_date: '',
        end_date: '',
        people_count: 2,
        target_calories: 2000,
        dietary_preferences: [],
        entries: []
      });
      setAutoGenerateData({
        start_date: '',
        days: 7,
        target_calories: 2000,
        people_count: 2,
        dietary_preferences: [],
        user_id: 1
      });
    }
  }, [editingMealPlan]);

  useEffect(() => {
    if (isOpen) {
      fetchRecipes();
    }
  }, [isOpen, fetchRecipes]);

  const dietaryOptions = [
    { value: 'vegetarian', label: 'Vegetarian' },
    { value: 'vegan', label: 'Vegan' },
    { value: 'gluten-free', label: 'Gluten Free' },
    { value: 'dairy-free', label: 'Dairy Free' },
    { value: 'keto', label: 'Keto' },
    { value: 'low-carb', label: 'Low Carb' },
    { value: 'high-protein', label: 'High Protein' },
  ];

  const mealTypeOptions = [
    { value: 'breakfast', label: 'Breakfast' },
    { value: 'lunch', label: 'Lunch' },
    { value: 'dinner', label: 'Dinner' },
    { value: 'snack', label: 'Snack' },
  ];

  const handleInputChange = (field: keyof MealPlanCreate, value: any) => {
    setFormData(prev => ({ ...prev, [field]: value }));
  };

  const handleAutoGenerateChange = (field: string, value: any) => {
    setAutoGenerateData(prev => ({ ...prev, [field]: value }));
  };

  const toggleDietaryPreference = (preference: string) => {
    if (isAutoGenerate) {
      setAutoGenerateData(prev => ({
        ...prev,
        dietary_preferences: prev.dietary_preferences.includes(preference)
          ? prev.dietary_preferences.filter(p => p !== preference)
          : [...prev.dietary_preferences, preference]
      }));
    } else {
      setFormData(prev => ({
        ...prev,
        dietary_preferences: prev.dietary_preferences.includes(preference)
          ? prev.dietary_preferences.filter(p => p !== preference)
          : [...prev.dietary_preferences, preference]
      }));
    }
  };

  const addMealEntry = () => {
    const newEntry: MealPlanEntryCreate = {
      recipe_id: 0,
      date: formData.start_date,
      meal_type: 'breakfast',
      servings: 1
    };
    setFormData(prev => ({
      ...prev,
      entries: [...prev.entries, newEntry]
    }));
  };

  const updateMealEntry = (index: number, field: keyof MealPlanEntryCreate, value: any) => {
    setFormData(prev => ({
      ...prev,
      entries: prev.entries.map((entry, i) => 
        i === index ? { ...entry, [field]: value } : entry
      )
    }));
  };

  const removeMealEntry = (index: number) => {
    setFormData(prev => ({
      ...prev,
      entries: prev.entries.filter((_, i) => i !== index)
    }));
  };

  const calculateEndDate = (startDate: string, days: number) => {
    const start = new Date(startDate);
    const end = new Date(start);
    end.setDate(start.getDate() + days - 1);
    return end.toISOString().split('T')[0];
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    
    try {
      if (isAutoGenerate && !isEditing) {
        await autoGenerate({
          ...autoGenerateData,
          start_date: autoGenerateData.start_date + 'T00:00:00',
        });
      } else {
        const mealPlanData = {
          ...formData,
          start_date: formData.start_date + 'T00:00:00',
          end_date: formData.end_date + 'T23:59:59',
          entries: formData.entries.map(entry => ({
            ...entry,
            date: entry.date + 'T00:00:00'
          }))
        };

        if (isEditing && editingMealPlan) {
          await updatePlan(editingMealPlan.id, mealPlanData);
        } else {
          await createPlan(mealPlanData);
        }
      }
      
      onSuccess();
      onClose();
      
      // Reset form only if not editing
      if (!isEditing) {
        setFormData({
          start_date: '',
          end_date: '',
          people_count: 2,
          target_calories: 2000,
          dietary_preferences: [],
          entries: []
        });
        setAutoGenerateData({
          start_date: '',
          days: 7,
          target_calories: 2000,
          people_count: 2,
          dietary_preferences: [],
          user_id: 1
        });
      }
    } catch (error) {
      console.error(`Failed to ${isEditing ? 'update' : 'create'} meal plan:`, error);
    }
  };

  const handleClose = () => {
    onClose();
    // Reset form when closing only if not editing
    if (!isEditing) {
      setFormData({
        start_date: '',
        end_date: '',
        people_count: 2,
        target_calories: 2000,
        dietary_preferences: [],
        entries: []
      });
      setAutoGenerateData({
        start_date: '',
        days: 7,
        target_calories: 2000,
        people_count: 2,
        dietary_preferences: [],
        user_id: 1
      });
    }
  };

  if (!isOpen) return null;

  const isLoading = creating || updating || autoGenerating;

  return (
    <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center p-4 z-50">
      <div className="bg-white rounded-lg shadow-xl max-w-4xl w-full max-h-[90vh] overflow-y-auto">
        <div className="flex items-center justify-between p-6 border-b border-neutral-200">
          <h2 className="text-xl font-semibold text-neutral-900">
            {isEditing ? 'Edit Meal Plan' : 'Create Meal Plan'}
          </h2>
          <button
            onClick={handleClose}
            className="text-neutral-400 hover:text-neutral-600 transition-colors"
          >
            <X className="h-6 w-6" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 space-y-6">
          {/* Mode Toggle - Only show for new meal plans */}
          {!isEditing && (
            <div className="flex space-x-4 mb-6">
              <button
                type="button"
                onClick={() => setIsAutoGenerate(false)}
                className={`px-4 py-2 rounded-md font-medium transition-colors ${
                  !isAutoGenerate
                    ? 'bg-primary-600 text-white'
                    : 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200'
                }`}
              >
                Manual Planning
              </button>
              <button
                type="button"
                onClick={() => setIsAutoGenerate(true)}
                className={`px-4 py-2 rounded-md font-medium transition-colors ${
                  isAutoGenerate
                    ? 'bg-primary-600 text-white'
                    : 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200'
                }`}
              >
                Auto Generate
              </button>
            </div>
          )}

          {isAutoGenerate && !isEditing ? (
            /* Auto Generate Form */
            <div className="space-y-4">
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <Input
                  label="Start Date"
                  type="date"
                  value={autoGenerateData.start_date}
                  onChange={(e) => handleAutoGenerateChange('start_date', e.target.value)}
                  leftIcon={<Calendar className="h-5 w-5" />}
                  required
                  fullWidth
                />
                
                <Input
                  label="Number of Days"
                  type="number"
                  value={autoGenerateData.days}
                  onChange={(e) => handleAutoGenerateChange('days', Number(e.target.value))}
                  min={1}
                  max={30}
                  required
                  fullWidth
                />
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <Input
                  label="People Count"
                  type="number"
                  value={autoGenerateData.people_count}
                  onChange={(e) => handleAutoGenerateChange('people_count', Number(e.target.value))}
                  leftIcon={<Users className="h-5 w-5" />}
                  min={1}
                  max={20}
                  required
                  fullWidth
                />
                
                <Input
                  label="Target Calories per Day"
                  type="number"
                  value={autoGenerateData.target_calories}
                  onChange={(e) => handleAutoGenerateChange('target_calories', Number(e.target.value))}
                  leftIcon={<Target className="h-5 w-5" />}
                  min={1000}
                  max={5000}
                  step={100}
                  required
                  fullWidth
                />
              </div>

              <div>
                <label className="block text-sm font-medium text-neutral-700 mb-2">
                  Dietary Preferences
                </label>
                <div className="flex flex-wrap gap-2">
                  {dietaryOptions.map((option) => (
                    <button
                      key={option.value}
                      type="button"
                      onClick={() => toggleDietaryPreference(option.value)}
                      className={`
                        inline-flex items-center rounded-full px-3 py-1 text-sm font-medium transition-colors
                        ${autoGenerateData.dietary_preferences.includes(option.value)
                          ? 'bg-primary-100 text-primary-800'
                          : 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200'
                        }
                      `}
                    >
                      {option.label}
                    </button>
                  ))}
                </div>
              </div>
            </div>
          ) : (
            /* Manual Form */
            <div className="space-y-6">
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <Input
                  label="Start Date"
                  type="date"
                  value={formData.start_date}
                  onChange={(e) => handleInputChange('start_date', e.target.value)}
                  leftIcon={<Calendar className="h-5 w-5" />}
                  required
                  fullWidth
                />
                
                <Input
                  label="End Date"
                  type="date"
                  value={formData.end_date}
                  onChange={(e) => handleInputChange('end_date', e.target.value)}
                  leftIcon={<Calendar className="h-5 w-5" />}
                  required
                  fullWidth
                />
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <Input
                  label="People Count"
                  type="number"
                  value={formData.people_count}
                  onChange={(e) => handleInputChange('people_count', Number(e.target.value))}
                  leftIcon={<Users className="h-5 w-5" />}
                  min={1}
                  max={20}
                  required
                  fullWidth
                />
                
                <Input
                  label="Target Calories per Day"
                  type="number"
                  value={formData.target_calories}
                  onChange={(e) => handleInputChange('target_calories', Number(e.target.value))}
                  leftIcon={<Target className="h-5 w-5" />}
                  min={1000}
                  max={5000}
                  step={100}
                  required
                  fullWidth
                />
              </div>

              <div>
                <label className="block text-sm font-medium text-neutral-700 mb-2">
                  Dietary Preferences
                </label>
                <div className="flex flex-wrap gap-2">
                  {dietaryOptions.map((option) => (
                    <button
                      key={option.value}
                      type="button"
                      onClick={() => toggleDietaryPreference(option.value)}
                      className={`
                        inline-flex items-center rounded-full px-3 py-1 text-sm font-medium transition-colors
                        ${formData.dietary_preferences.includes(option.value)
                          ? 'bg-primary-100 text-primary-800'
                          : 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200'
                        }
                      `}
                    >
                      {option.label}
                    </button>
                  ))}
                </div>
              </div>

              {/* Meal Entries */}
              <div>
                <div className="flex items-center justify-between mb-4">
                  <h3 className="text-lg font-medium text-neutral-900">Meal Entries</h3>
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    onClick={addMealEntry}
                    leftIcon={<Plus className="h-4 w-4" />}
                  >
                    Add Meal
                  </Button>
                </div>

                <div className="space-y-4">
                  {formData.entries.map((entry, index) => (
                    <Card key={index}>
                      <CardContent className="p-4">
                        <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
                          <div className="md:col-span-2">
                            <label className="block text-sm font-medium text-neutral-700 mb-1">
                              Recipe
                            </label>
                            <RecipeSearchSelect
                              value={entry.recipe_id}
                              onChange={(recipeId) => updateMealEntry(index, 'recipe_id', recipeId)}
                              placeholder="Search for recipe..."
                            />
                          </div>
                          
                          <Input
                            label="Date"
                            type="date"
                            value={entry.date}
                            onChange={(e) => updateMealEntry(index, 'date', e.target.value)}
                            fullWidth
                          />
                          
                          <Select
                            label="Meal Type"
                            options={mealTypeOptions}
                            value={entry.meal_type}
                            onChange={(value) => updateMealEntry(index, 'meal_type', value)}
                            fullWidth
                          />
                          
                          <div className="flex items-end space-x-2">
                            <Input
                              label="Servings"
                              type="number"
                              value={entry.servings}
                              onChange={(e) => updateMealEntry(index, 'servings', Number(e.target.value))}
                              min={1}
                              max={20}
                              fullWidth
                            />
                            <Button
                              type="button"
                              variant="outline"
                              size="sm"
                              onClick={() => removeMealEntry(index)}
                              className="text-error-600 hover:text-error-700"
                            >
                              <Trash2 className="h-4 w-4" />
                            </Button>
                          </div>
                        </div>
                      </CardContent>
                    </Card>
                  ))}
                  
                  {formData.entries.length === 0 && (
                    <div className="text-center py-8 text-neutral-500">
                      No meal entries added yet. Click "Add Meal" to get started.
                    </div>
                  )}
                </div>
              </div>
            </div>
          )}

          {/* Form Actions */}
          <div className="flex justify-end space-x-3 pt-6 border-t border-neutral-200">
            <Button type="button" variant="outline" onClick={handleClose}>
              Cancel
            </Button>
            <Button 
              type="submit" 
              isLoading={isLoading}
              disabled={
                isAutoGenerate && !isEditing
                  ? !autoGenerateData.start_date || autoGenerateData.days < 1
                  : !formData.start_date || !formData.end_date || formData.entries.length === 0
              }
            >
              {isEditing 
                ? 'Update Meal Plan' 
                : isAutoGenerate 
                  ? 'Generate Meal Plan' 
                  : 'Create Meal Plan'
              }
            </Button>
          </div>
        </form>
      </div>
    </div>
  );
};

export default CreateMealPlanModal;